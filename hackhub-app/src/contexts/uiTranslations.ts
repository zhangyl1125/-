const dynamicTranslations: Array<[RegExp, (...matches: string[]) => string]> = [
  [/^(\d+) participants?$/i, (count) => `${count} 位参与者`],
  [/^(\d+) members?$/i, (count) => `${count} 位成员`],
  [/^(\d+) teams?$/i, (count) => `${count} 个团队`],
  [/^(\d+) ideas?$/i, (count) => `${count} 个创意`],
  [/^(\d+) votes?$/i, (count) => `${count} 票`],
  [/^(\d+) days? left$/i, (count) => `剩余 ${count} 天`],
  [/^(\d+) days? remaining$/i, (count) => `剩余 ${count} 天`],
  [/^Starts in (.+)$/i, (value) => `${value} 后开始`],
  [/^Ends (.+)$/i, (value) => `${value} 结束`],
  [/^Created: (.+)$/i, (value) => `创建时间：${value}`],
  [/^Created by: (.+)$/i, (value) => `创建者：${value}`],
  [/^Prize #(\d+)$/i, (count) => `奖项 ${count}`],
  [/^You joined (.+)$/i, (value) => `您已加入 ${value}`],
  [/^(.+) weighted avg$/i, (value) => `${value} 加权平均分`],
]

export function translateUiText(value: string) {
  const leadingWhitespace = value.match(/^\s*/)?.[0] ?? ''
  const trailingWhitespace = value.match(/\s*$/)?.[0] ?? ''
  const content = value.trim()

  if (!content) return value

  const exactTranslation = uiTranslations[content]
  if (exactTranslation) return `${leadingWhitespace}${exactTranslation}${trailingWhitespace}`

  for (const [pattern, translate] of dynamicTranslations) {
    const match = content.match(pattern)
    if (match) return `${leadingWhitespace}${translate(...match.slice(1))}${trailingWhitespace}`
  }

  return value
}
